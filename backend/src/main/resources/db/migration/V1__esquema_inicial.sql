-- FocusMood - Modelo relacional (documento seccion 4.4). SQL portable PostgreSQL/H2.

CREATE TABLE usuario (
    id_usuario      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(120) NOT NULL,
    correo          VARCHAR(150) NOT NULL,
    contrasena_hash VARCHAR(255) NOT NULL,
    fecha_registro  TIMESTAMP WITH TIME ZONE NOT NULL,
    activo          BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_usuario_correo UNIQUE (correo)
);

CREATE TABLE perfil (
    id_perfil    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario   BIGINT NOT NULL,
    carrera      VARCHAR(120),
    semestre     SMALLINT,
    preferencias TEXT,
    foto_perfil  VARCHAR(500),
    CONSTRAINT uk_perfil_usuario UNIQUE (id_usuario),
    CONSTRAINT fk_perfil_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    CONSTRAINT ck_perfil_semestre CHECK (semestre IS NULL OR semestre BETWEEN 1 AND 20)
);

-- Extension al modelo: tokens de recuperacion de contrasena (FCM-03). Solo se guarda el hash.
CREATE TABLE token_recuperacion (
    id_token    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario  BIGINT NOT NULL,
    token_hash  VARCHAR(64) NOT NULL,
    expira_en   TIMESTAMP WITH TIME ZONE NOT NULL,
    usado       BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_token_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE CASCADE
);

CREATE TABLE registro_diario (
    id_registro         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario          BIGINT NOT NULL,
    fecha               DATE NOT NULL,
    fecha_hora          TIMESTAMP WITH TIME ZONE NOT NULL,
    estado_animo        VARCHAR(30) NOT NULL,
    nivel_energia       SMALLINT NOT NULL,
    nivel_concentracion SMALLINT NOT NULL,
    observacion         VARCHAR(500),
    CONSTRAINT uk_registro_usuario_fecha UNIQUE (id_usuario, fecha),
    CONSTRAINT fk_registro_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    CONSTRAINT ck_registro_energia CHECK (nivel_energia BETWEEN 1 AND 5),
    CONSTRAINT ck_registro_concentracion CHECK (nivel_concentracion BETWEEN 1 AND 5)
);

CREATE TABLE solicitud_recomendacion (
    id_solicitud        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_registro         BIGINT NOT NULL,
    fecha_hora          TIMESTAMP WITH TIME ZONE NOT NULL,
    tiempo_disponible   SMALLINT NOT NULL,
    actividad_academica VARCHAR(200) NOT NULL,
    CONSTRAINT fk_solicitud_registro FOREIGN KEY (id_registro) REFERENCES registro_diario (id_registro) ON DELETE CASCADE,
    CONSTRAINT ck_solicitud_tiempo CHECK (tiempo_disponible > 0)
);

-- Extension: columnas titulo, tecnica y duracion_minutos para cumplir RF-10 sin parsear texto libre.
CREATE TABLE recomendacion (
    id_recomendacion  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud      BIGINT NOT NULL,
    titulo            VARCHAR(150) NOT NULL,
    tecnica           VARCHAR(100) NOT NULL,
    duracion_minutos  SMALLINT NOT NULL,
    contenido         TEXT NOT NULL,
    categoria         VARCHAR(50),
    fecha_generacion  TIMESTAMP WITH TIME ZONE NOT NULL,
    modelo_ia         VARCHAR(80),
    CONSTRAINT uk_recomendacion_solicitud UNIQUE (id_solicitud),
    CONSTRAINT fk_recomendacion_solicitud FOREIGN KEY (id_solicitud) REFERENCES solicitud_recomendacion (id_solicitud) ON DELETE CASCADE,
    CONSTRAINT ck_recomendacion_duracion CHECK (duracion_minutos > 0)
);

CREATE TABLE calificacion (
    id_calificacion    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_recomendacion   BIGINT NOT NULL,
    puntuacion         SMALLINT NOT NULL,
    comentario         VARCHAR(500),
    fecha_calificacion TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_calificacion_recomendacion UNIQUE (id_recomendacion),
    CONSTRAINT fk_calificacion_recomendacion FOREIGN KEY (id_recomendacion) REFERENCES recomendacion (id_recomendacion) ON DELETE CASCADE,
    CONSTRAINT ck_calificacion_puntuacion CHECK (puntuacion BETWEEN 1 AND 5)
);

CREATE TABLE habito (
    id_habito    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario   BIGINT NOT NULL,
    nombre       VARCHAR(100) NOT NULL,
    descripcion  VARCHAR(500),
    frecuencia   VARCHAR(30) NOT NULL,
    horario      VARCHAR(20),
    fecha_inicio DATE NOT NULL,
    activo       BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_habito_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE CASCADE
);

CREATE TABLE cumplimiento_habito (
    id_cumplimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_habito       BIGINT NOT NULL,
    fecha           DATE NOT NULL,
    cumplido        BOOLEAN NOT NULL DEFAULT TRUE,
    observacion     VARCHAR(500),
    CONSTRAINT uk_cumplimiento_habito_fecha UNIQUE (id_habito, fecha),
    CONSTRAINT fk_cumplimiento_habito FOREIGN KEY (id_habito) REFERENCES habito (id_habito) ON DELETE CASCADE
);

CREATE TABLE sesion_estudio (
    id_sesion        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario       BIGINT NOT NULL,
    fecha_inicio     TIMESTAMP WITH TIME ZONE NOT NULL,
    fecha_fin        TIMESTAMP WITH TIME ZONE,
    actividad        VARCHAR(200) NOT NULL,
    duracion_minutos SMALLINT NOT NULL,
    estado           VARCHAR(20) NOT NULL,
    CONSTRAINT uk_sesion_usuario_inicio UNIQUE (id_usuario, fecha_inicio),
    CONSTRAINT fk_sesion_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    CONSTRAINT ck_sesion_duracion CHECK (duracion_minutos > 0)
);

CREATE TABLE ciclo_pomodoro (
    id_pomodoro            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sesion              BIGINT NOT NULL,
    duracion_concentracion SMALLINT NOT NULL,
    duracion_descanso      SMALLINT NOT NULL,
    ciclos_completados     SMALLINT NOT NULL,
    estado                 VARCHAR(20) NOT NULL,
    CONSTRAINT fk_pomodoro_sesion FOREIGN KEY (id_sesion) REFERENCES sesion_estudio (id_sesion) ON DELETE CASCADE,
    CONSTRAINT ck_pomodoro_concentracion CHECK (duracion_concentracion > 0),
    CONSTRAINT ck_pomodoro_descanso CHECK (duracion_descanso > 0),
    CONSTRAINT ck_pomodoro_ciclos CHECK (ciclos_completados >= 0)
);

CREATE TABLE actividad_bienestar (
    id_actividad      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            VARCHAR(120) NOT NULL,
    descripcion       TEXT NOT NULL,
    categoria         VARCHAR(50) NOT NULL,
    duracion_estimada SMALLINT NOT NULL,
    activa            BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_actividad_duracion CHECK (duracion_estimada > 0)
);

CREATE TABLE registro_bienestar (
    id_registro_bienestar BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario            BIGINT NOT NULL,
    id_actividad          BIGINT NOT NULL,
    fecha_realizacion     TIMESTAMP WITH TIME ZONE NOT NULL,
    completada            BOOLEAN NOT NULL,
    observacion           VARCHAR(500),
    CONSTRAINT fk_rbienestar_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_rbienestar_actividad FOREIGN KEY (id_actividad) REFERENCES actividad_bienestar (id_actividad)
);

CREATE TABLE recordatorio (
    id_recordatorio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario      BIGINT NOT NULL,
    id_habito       BIGINT,
    titulo          VARCHAR(120) NOT NULL,
    tipo            VARCHAR(30) NOT NULL,
    fecha_hora      TIMESTAMP WITH TIME ZONE NOT NULL,
    frecuencia      VARCHAR(30),
    activo          BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_recordatorio_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_recordatorio_habito FOREIGN KEY (id_habito) REFERENCES habito (id_habito) ON DELETE CASCADE
);

CREATE INDEX idx_habito_usuario ON habito (id_usuario);
CREATE INDEX idx_rbienestar_usuario_fecha ON registro_bienestar (id_usuario, fecha_realizacion);
CREATE INDEX idx_recordatorio_usuario ON recordatorio (id_usuario);
